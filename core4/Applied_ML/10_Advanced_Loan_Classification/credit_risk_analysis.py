# Target column: 1 = defaulted ("bad"), 0 = repaid ("good")
y = (df["class"].astype(str) == "bad").astype(int)

# Features
X = df.drop(columns="class")
# How much the borrower must pay back each month
X["monthly_payment"] = X["credit_amount"] / X["duration"]

print(f"{len(X)} applicants, {X.shape[1]} details, default rate = {y.mean():.1%}")

