"""## 9. A machine-learning sentiment model

**Task.** Predict a passage's sentiment class from its words alone.

**Why do this if VADER already scores the text?** (a) It tests whether the sentiment is predictable from vocabulary. (b) The trained model can read texts without the lexicon. (c) Its coefficients show which words push a passage toward each class, including words the lexicon does not know.

**Design**

- **Features:** TF-IDF of single words and word pairs, with negations kept (Section 4). Vectorisation happens **inside** a scikit-learn `Pipeline`, so each fold learns its vocabulary only from its own training data.
- **Split by speech, not by passage** (`GroupKFold`): every speech stays entirely on one side.
- **Metric:** macro-F1 (average F1 over the classes), because the classes are unbalanced and accuracy would hide poor performance on the small ones.
- **Baseline:** a classifier that always predicts the most frequent class.

### 9.1 Why the task is reduced to two classes
"""

passages_df["tokens"] = passages_df["text"].map(lambda t: " ".join(prepare(t, for_sentiment=True)))

def make_model(clf):
    return Pipeline([
        ("tfidf", TfidfVectorizer(token_pattern=r"[a-z]+", lowercase=False,
                                  ngram_range=(1, 2), min_df=3, sublinear_tf=True)),
        ("clf", clf),
    ])

cv5 = GroupKFold(n_splits=5)       # deterministic: speeches are assigned to folds by size

print(passages_df["label"].value_counts().to_string(), "\n")
