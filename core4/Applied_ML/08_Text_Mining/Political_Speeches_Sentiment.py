"""### 5.1 Comparing historical eras

The speeches are grouped into four eras. The boundaries follow major turning points in U.S. history; they are a modelling choice, so the notebook reports how many speeches fall into each.

| Era | Years | Context |
|---|---|---|
| Era 1 | 1789–1859 | Early republic, up to the eve of the Civil War |
| Era 2 | 1860–1932 | Civil War, Reconstruction, industrialisation, World War I, up to the Great Depression |
| Era 3 | 1933–1988 | New Deal, World War II, Cold War |
| Era 4 | 1989–2025 | Post-Cold-War era |

For each era the notebook lists its **most distinctive words**. Plain frequency would just return *government* and *people* four times. Instead it uses the **weighted log-odds ratio with an informative Dirichlet prior** (Monroe, Colaresi & Quinn, 2008): each word's frequency in one era is compared with its frequency in the other three, the corpus-wide frequency serves as a prior, and the result is a z-score, so rare words with weak evidence are damped down automatically. (Plain TF-IDF would be a poor choice here: with only four "documents", its inverse-document-frequency term has just four possible values.)
"""

ERAS = {                      # inclusive start, exclusive end
    "Era 1": (1789, 1860),
    "Era 2": (1860, 1933),
    "Era 3": (1933, 1989),
    "Era 4": (1989, 2100),
}
era_names = list(ERAS)

def era_of(year):
    for name, (start, end) in ERAS.items():
        if start <= year < end:
            return name
    raise ValueError(f"year {year} is outside all eras")

speeches["era"] = speeches["year"].map(era_of)

display(speeches.groupby("era").agg(speeches=("year", "size"), first=("year", "min"),
                                    last=("year", "max"), words=("n_words", "sum")).loc[era_names])

# One count vector per era (rows = eras, columns = words)
era_docs = [" ".join(w for toks in speeches.loc[speeches["era"] == e, "tokens"] for w in toks)
            for e in era_names]
cv = CountVectorizer(token_pattern=r"[a-z]+", lowercase=False)
M = cv.fit_transform(era_docs).toarray().astype(float)
vocab = np.array(cv.get_feature_names_out())
total = M.sum(axis=0)

ALPHA0 = 500                              # strength of the prior (in pseudo-counts)
prior = ALPHA0 * total / total.sum()

def log_odds_z(i, min_count=5):
    """z-score of each word's log-odds in era i versus the other eras (Monroe et al. 2008)."""
    a, b = M[i], total - M[i]
    n_a, n_b, a0 = a.sum(), b.sum(), prior.sum()
    la = np.log((a + prior) / (n_a + a0 - a - prior))
    lb = np.log((b + prior) / (n_b + a0 - b - prior))
    z = (la - lb) / np.sqrt(1 / (a + prior) + 1 / (b + prior))
    z[total < min_count] = -np.inf        # ignore words seen fewer than 5 times in the corpus
    return z

distinct = {}
for i, e in enumerate(era_names):
    z = log_odds_z(i)
    top = np.argsort(z)[::-1][:40]
    distinct[e] = {vocab[j]: float(z[j]) for j in top if z[j] > 0}

display(pd.DataFrame({e: pd.Series(list(d)[:12]) for e, d in distinct.items()}))

