"""### 9.3 Tuning the decision threshold without cheating

Logistic regression returns a probability of "negative". The default cut-off of 0.5 usually finds too few negative passages, so the cut-off is tuned for macro-F1. Choosing it on the same predictions that are then scored gives an optimistic result, so the tuning is **nested**: inside each outer training set, the threshold is chosen from inner out-of-fold probabilities, and the outer test fold is scored with that threshold without ever having influenced it.
"""

THRESH_GRID = np.round(np.arange(0.20, 0.81, 0.05), 2)
def lr_model():
    return make_model(LogisticRegression(max_iter=2000, class_weight="balanced"))

def pick_threshold(X, y, groups, n_splits=4):
    """Choose the threshold that maximises macro-F1 on inner out-of-fold probabilities."""
    p = cross_val_predict(lr_model(), X, y, groups=groups, cv=GroupKFold(n_splits=n_splits),
                          method="predict_proba")[:, 1]
    scores = [f1_score(y, (p >= t).astype(int), average="macro") for t in THRESH_GRID]
    return float(THRESH_GRID[int(np.argmax(scores))])

p_oof = np.zeros(len(yb))
pred_nested = np.zeros(len(yb), dtype=int)
chosen = []
for train_idx, test_idx in GroupKFold(n_splits=5).split(Xb, yb, gb):
    t = pick_threshold(Xb.iloc[train_idx], yb.iloc[train_idx], gb.iloc[train_idx])
    fitted = lr_model().fit(Xb.iloc[train_idx], yb.iloc[train_idx])
    p_oof[test_idx] = fitted.predict_proba(Xb.iloc[test_idx])[:, 1]
    pred_nested[test_idx] = (p_oof[test_idx] >= t).astype(int)
    chosen.append(t)

