draw(axes[2], "we_per_1000", "we", "tab:red")
draw(axes[2], "i_per_1000", "I", "tab:gray")
axes[2].set_ylabel("Per 1,000 tokens"); axes[2].set_title('"We" versus "I"')
axes[2].legend(); axes[2].set_xlabel("Year")
