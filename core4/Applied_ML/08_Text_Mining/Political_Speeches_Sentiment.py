"""## 4. Tokenization and stop-word removal

**Tokenization** cuts the cleaned text into words. A regex does the job: `[a-z]+` keeps runs of letters.

**Stop words** are very common words (*the, of, and, to*) that carry little topical meaning. Removing them makes counts and word clouds far more informative. Two points of care:

- **A domain list is added.** Words such as *shall*, *upon* or *mr* appear in almost every address as ritual language.
- **Negations are protected for sentiment.** The standard list contains *not*, *no* and *never*. For word clouds they are removed; for sentiment they are essential, so the sentiment model uses a second list that keeps them.
"""

# Negations and near-negations that sentiment analysis needs
NEGATIONS = {"not", "no", "never", "none", "nobody", "nothing", "nowhere",
             "neither", "nor", "cannot", "without"}

# Ritual words that appear in nearly every address
DOMAIN_STOPWORDS = {"shall", "upon", "mr", "mrs", "ms", "dr", "let", "us",
                    "must", "will", "would", "may", "also"}

# Counts / word clouds: standard list + domain list (negations removed too)
STOPWORDS_COUNTS = set(ENGLISH_STOP_WORDS) | DOMAIN_STOPWORDS | NEGATIONS

# Sentiment: same list, but negations are kept
STOPWORDS_SENTIMENT = (set(ENGLISH_STOP_WORDS) | DOMAIN_STOPWORDS) - NEGATIONS

def tokenize(text):
    """Cut cleaned text into lowercase letter-only tokens."""
    return re.findall(r"[a-z]+", text)

def remove_stopwords(tokens, stopwords):
    return [t for t in tokens if t not in stopwords]

def prepare(text, for_sentiment=False):
    tokens = tokenize(clean_text(text))
    stops = STOPWORDS_SENTIMENT if for_sentiment else STOPWORDS_COUNTS
    return remove_stopwords(tokens, stops)

